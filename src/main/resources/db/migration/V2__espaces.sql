CREATE TABLE batiments (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom  VARCHAR(150) NOT NULL,
    CONSTRAINT uk_batiments_nom UNIQUE (nom)
);

CREATE TABLE espaces (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(50) NOT NULL,
    nom          VARCHAR(150) NOT NULL,
    type         VARCHAR(30) NOT NULL,
    capacite     INTEGER NOT NULL,
    batiment_id  BIGINT NOT NULL,
    etage        INTEGER,
    description  VARCHAR(2000),
    statut       VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    archive      BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_espaces_code UNIQUE (code),
    CONSTRAINT ck_espaces_code_normalise CHECK (code = UPPER(TRIM(code))),
    CONSTRAINT ck_espaces_nom CHECK (TRIM(nom) <> ''),
    CONSTRAINT ck_espaces_capacite CHECK (capacite > 0),
    CONSTRAINT ck_espaces_type CHECK (type IN ('CLASSROOM', 'COMPUTER_LAB', 'MEETING_ROOM', 'AMPHITHEATER', 'STUDY_ROOM', 'OTHER')),
    CONSTRAINT ck_espaces_statut CHECK (statut IN ('ACTIVE', 'MAINTENANCE')),
    CONSTRAINT fk_espaces_batiment_id FOREIGN KEY (batiment_id) REFERENCES batiments(id) ON DELETE RESTRICT
);

CREATE INDEX idx_espaces_batiment_id ON espaces (batiment_id);
CREATE INDEX idx_espaces_statut_archive ON espaces (statut, archive);
