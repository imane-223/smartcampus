-- Comptes utilisateurs : une seule table pour les trois roles (heritage SINGLE_TABLE).
-- La colonne role sert de discriminateur JPA.
-- SQL portable PostgreSQL / H2 (mode PostgreSQL) : voir docs/conventions.md.

CREATE TABLE utilisateurs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courriel             VARCHAR(255)             NOT NULL,
    mot_de_passe_hash    VARCHAR(100)             NOT NULL,
    prenom               VARCHAR(100)             NOT NULL,
    nom                  VARCHAR(100)             NOT NULL,
    role                 VARCHAR(20)              NOT NULL,
    actif                BOOLEAN                  NOT NULL DEFAULT TRUE,
    changer_mot_de_passe BOOLEAN                  NOT NULL DEFAULT FALSE,
    tentatives_echouees  INTEGER                  NOT NULL DEFAULT 0,
    verrouille_jusqu_a   TIMESTAMP WITH TIME ZONE,
    cree_le              TIMESTAMP WITH TIME ZONE NOT NULL,

    -- Etudiant et enseignant
    numero               VARCHAR(50),
    -- Etudiant
    code_massar          VARCHAR(20),
    filiere              VARCHAR(100),
    -- Enseignant
    code_enseignant      VARCHAR(20),
    grade                VARCHAR(50),
    specialite           VARCHAR(100),

    -- La contrainte unique cree l'index utilise par la recherche par courriel
    CONSTRAINT uk_utilisateurs_courriel UNIQUE (courriel),
    CONSTRAINT ck_utilisateurs_role CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN')),
    CONSTRAINT ck_utilisateurs_courriel_minuscules CHECK (courriel = LOWER(courriel))
);
